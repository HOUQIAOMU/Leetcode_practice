#include <iostream>
#include <vector>
#include <queue>
using namespace std;

// 这道题用到了一个核心数据结构：单调队列。

// 过程：（为演示，这里队列内容直接用的数值，实际上是下标）
// 新进入元素	单调队列（值）	当前窗口最大值
// 1	[1]	窗口未形成
// 3	[3]	窗口未形成
// -1	[3, -1]	3
// -3	[3, -1, -3]	3
// 5	[5]	5
// 3	[5, 3]	5
// 6	[6]	6
// 7	[7]	7
vector<int> maxSlidingWindow(vector<int>& nums, int k){
    // 为了便于计算，我们要动态维护当前窗口内的最大值，又要省计算，不用每次都判断谁最大
    // 那么，我们就要只保留未来可能成为最大值的元素，删除不必要的一些元素
    // 这个思想用到了单调队列，队列里存储元素下标
    // [队头，次大候选值，...]，保持单调递减
    // 单调队列如何维护？1.保持单调递减，每遍历到一个元素，判断其大小所在位置，并从队尾删除更小的元素
    // 2.要删掉下标不符合要求的元素，保证窗口只有3个

    vector<int> ans={};
    deque<int> dq; // 用此队列存放元素下标
    for(int i = 0; i < nums.size(); i++){
        // 1.先删除队列里下标不满足窗口大小的元素，保证窗口
        // 由于队列是先进先出，所以队头一定是最早的元素，最应该出去的
        while(!dq.empty() && dq.front() < i-k+1){
            dq.pop_front(); // 把队头的，不满足i-k+1下标要求的弹出去
        }
        // 2. 删掉队列里比当前遍历元素小的元素，因为这些元素又要比当前元素先pop，又比当前元素小，所以一定不可能成为最大值
        while(!dq.empty() && nums[i] >= nums[dq.back()]){
            // 从队尾开始判断，因为队尾的元素最小
            dq.pop_back();
        }
        // 删掉较小元素后，把下标i放到队列中
        dq.push_back(i);
        // i形成窗口之后，就可以开始判断窗口最大值了
        if(i-k+1 >=0){
            ans.push_back(nums[dq.front()]); // 因为dq.front()一定是最大的元素对应的下标
        }
    }
    return ans;
}
